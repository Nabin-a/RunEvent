export function policyLabelTh(policy?: FormFieldPolicy): string {
  switch (policy) {
    case 'LOCKED':
      return tx('LOCKED (ล็อกโดยระบบ ห้ามผู้จัดแก้/ลบ)');
    case 'CONFIGURABLE':
      return tx('CONFIGURABLE (ผู้จัดปรับป้ายชื่อ/Required ได้)');
    case 'CUSTOMIZABLE':
    default:
      return tx('CUSTOMIZABLE (ผู้จัดเปิด/ปิดหรือปรับตัวเลือกในขอบเขตได้)');
  }
}
